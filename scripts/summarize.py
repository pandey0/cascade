"""Build results/SUMMARY.md from the experiment JSON files (no hand-copied numbers)."""

from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).resolve().parents[1] / "results"
SETTINGS = [
    ("Banking77, alpha=0.05", "exp1a_banking77_alpha005.json"),
    ("Banking77, alpha=0.03", "exp1a_banking77_alpha003.json"),
    ("CLINC150, alpha=0.02", "exp1a_clinc150_alpha002.json"),
    ("Synthetic, alpha=0.05", "exp0_alpha005.json"),
    ("Synthetic, alpha=0.10", "exp0_alpha010.json"),
]
METHODS = (
    "naive",
    "safety80",
    "wilson",
    "certify_once",
    "strict_sequence",
    "bonferroni",
    "holm",
    "split_sequence",
)
SIZES = {"real": (500, 1000, 2000), "syn": (500, 1000, 3000)}


def main() -> None:
    out = [
        "# Summary of informative settings (generated by scripts/summarize.py)\n",
        "Violation = share of calibration draws whose chosen threshold had true risk > alpha "
        "(guarantee: <= delta = 0.10). Coverage = share of traffic accepted (0 if not deployed). "
        "Real runs: mean over 3 student/pool splits, 400 draws each; synthetic: 500 draws.\n",
        "| setting | m | method | deploy | violation | coverage |\n|---|---|---|---|---|---|",
    ]
    for label, fname in SETTINGS:
        rows = json.loads((R / fname).read_text())
        sizes = SIZES["syn" if "exp0" in fname else "real"]
        for m in sizes:
            for method in METHODS:
                r = next(x for x in rows if x["m"] == m and x["method"] == method)
                out.append(
                    f"| {label} | {m} | {method} | {r['deploy_rate']:.2f} | "
                    f"{r['violation_rate_all']:.3f} | {r['mean_coverage']:.3f} |"
                )
    (R / "SUMMARY.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
